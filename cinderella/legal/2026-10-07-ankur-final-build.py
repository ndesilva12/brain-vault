def sub(doc, old, new, *, label, where=None):
    """Replace the first occurrence of `old` across runs. Asserts exactly one paragraph hit."""
    hits = 0
    for para in doc.paragraphs:
        if old not in para.text or (where and where not in para.text):
            continue
        runs, found = para.runs, False
        for i in range(len(runs)):
            acc = ""
            for j in range(i, len(runs)):
                acc += runs[j].text
                if old in acc:
                    head, _, tail = acc.partition(old)
                    runs[i].text = head + new + tail
                    for k in range(i + 1, j + 1):
                        runs[k].text = ""
                    found = True
                    break
            if found:
                break
        assert found, f"{label}: text present in paragraph but in no run span"
        hits += 1
        break
    assert hits == 1, f"{label}: expected 1 hit, got {hits}\n  needle: {old[:120]!r}"
    FIRED.append(label)


def find(doc, needle, *, label):
    for para in doc.paragraphs:
        if needle in para.text:
            return para
    raise AssertionError(f"{label}: paragraph not found: {needle[:90]!r}")


def drop(doc, needle, *, label):
    """Delete the paragraph containing `needle`."""
    para = find(doc, needle, label=label)
    para._p.getparent().remove(para._p)
    FIRED.append(label)


def insert_after(doc, anchor, lead, body, *, label):
    """Clone the paragraph containing `anchor` and insert a new one directly after it."""
    src = find(doc, anchor, label=label)
    new_p = copy.deepcopy(src._p)
    src._p.addnext(new_p)
    np = Paragraph(new_p, src._parent)
    assert np.runs, f"{label}: clone has no runs"
    if len(np.runs) == 1:
        # anchor is a single-run paragraph; clone its run so the lead can be bolded separately
        np.runs[0]._r.addnext(copy.deepcopy(np.runs[0]._r))
    np.runs[0].text = lead
    np.runs[0].bold = True
    np.runs[1].text = body
    np.runs[1].bold = False
    for r in np.runs[2:]:
        r.text = ""
    FIRED.append(label)
    return np


def append_doc_after(doc, anchor, policy_path, *, label, skip=0):
    """Append every paragraph of `policy_path` after the paragraph containing `anchor`,
    carrying its own formatting across (deep copy of the source XML)."""
    src = find(doc, anchor, label=label)
    cursor = src._p
    n = 0
    for p in Document(policy_path).paragraphs[skip:]:
        clone = copy.deepcopy(p._p)
        cursor.addnext(clone)
        cursor = clone
        n += 1
    assert n > 20, f"{label}: only {n} paragraphs appended, expected the full policy"
    FIRED.append(f"{label} ({n} paras)")
    return n


